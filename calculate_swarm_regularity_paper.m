function [autocorr_score] = calculate_swarm_regularity_paper(X, Y, m, method_type)
% CALCULATE_SWARM_REGULARITY_PAPER 严格按论文公式实现的自相关计算
% 
% 对应论文第一篇 Section 3 的三种变体:
%   method_type = 1: 距离自相关 (公式 3, Section 3.1)
%   method_type = 2: 修正距离自相关 (公式 7, Section 3.2)
%   method_type = 3: 差分自相关 (公式 8, Section 3.3)
%
% 输入:
%   X, Y     - N×1 坐标向量
%   m        - 邻居数量 (论文中 m ∈ [6,10])
%   method_type - 变体编号 (1/2/3)
%
% 输出:
%   autocorr_score - 标量自相关值 corr (公式 6)
%
% 注意: 本函数严格遵循论文原文，所有变体使用相同的 m 值。
%        不做任何 m 的局部化修改。

    N = length(X);
    if N < m + 1
        autocorr_score = 0;
        return;
    end
    
    % ============================================================
    % Step 1: 计算成对距离矩阵 R (论文公式 2)
    % ============================================================
    coords = [X(:), Y(:)];
    dist_mat = pdist2(coords, coords);  % N×N 距离矩阵
    
    % ============================================================
    % Step 2: 对每列排序，提取前 m 个最近邻距离 (论文公式 3)
    % R_star(j,k) = r*_{jk}, 即无人机k到第j近邻的距离
    % ============================================================
    sorted_dist = sort(dist_mat, 1, 'ascend');
    R_star = sorted_dist(2:m+1, :);  % m×N, 排除自身(第1行为0)
    
    % ============================================================
    % Step 3: 根据变体类型构建相对位置矩阵 B (论文 Section 3.1-3.3)
    % ============================================================
    switch method_type
        case 1
            % 变体1: 距离自相关 (Section 3.1)
            % B[k] = [r*_1k, r*_2k, ..., r*_mk]^T
            B = R_star;
            
        case 2
            % 变体2: 修正距离自相关 (Section 3.2, 公式 7)
            % r_bar_j = (1/N) * sum_k(r*_jk)  -- 第j近邻的全局平均距离
            % b_jk = r*_jk - r_bar_j
            r_bar = mean(R_star, 2);  % m×1, 每个邻居序位的平均距离
            B = R_star - r_bar;       % m×N, 减去平均距离
            
        case 3
            % 变体3: 差分自相关 (Section 3.3, 公式 8)
            % Delta[k] = [r*_1k, r*_2k - r*_1k, ..., r*_mk - r*_{m-1,k}]^T
            B = zeros(size(R_star));
            B(1, :) = R_star(1, :);                 % 第一行: 最近邻距离
            B(2:end, :) = diff(R_star, 1, 1);       % 后续行: 相邻邻居距离差
    end
    
    % ============================================================
    % Step 4: 计算 Pearson 相关矩阵 (论文公式 5)
    % corr_{k,l} 度量无人机 k 和 l 的空间位置相似性
    % ============================================================
    corr_mat = corr(B, 'Type', 'Pearson');  % N×N 相关矩阵
    
    % ============================================================
    % Step 5: 处理 NaN
    % 当某列方差为零时 (所有邻居等距), Pearson 相关未定义
    % 论文未明确说明处理方式; 设为 0 (中性, 不影响均值判断)
    % ============================================================
    corr_mat(isnan(corr_mat)) = 0;
    
    % ============================================================
    % Step 6: 计算全局自相关 (论文公式 6)
    % corr = (1/N^2) * sum_k sum_l corr_{k,l}
    % ============================================================
    autocorr_score = mean(corr_mat(:));
end
